CREATE TABLE PESSOA(
cpf VARCHAR (11) PRIMARY KEY,
nome VARCHAR (100),
sexo VARCHAR(100),
telefone VARCHAR(20),
email VARCHAR(100),
data_nascimento DATE
);

CREATE TABLE FUNCIONARIO(
fcpf VARCHAR (11) PRIMARY KEY REFERENCES PESSOA (cpf),
salario NUMERIC (10, 2),
horas_trabalhadas NUMERIC (5,2)
);

CREATE TABLE ADMINISTRADOR (
acpf VARCHAR(11) PRIMARY KEY REFERENCES FUNCIONARIO (fcpf)
);

CREATE TABLE DEPARTAMENTO (
dnome VARCHAR(50) PRIMARY KEY,
cpf_administrador VARCHAR(11) UNIQUE REFERENCES ADMINISTRADOR (acpf)
);

CREATE TABLE MEDICO(
crm VARCHAR(20) PRIMARY KEY,
mcpf VARCHAR(11) REFERENCES FUNCIONARIO (fcpf)
);

CREATE TABLE ENFERMEIRO(
coren VARCHAR(20) PRIMARY KEY,
ecpf VARCHAR(11) REFERENCES FUNCIONARIO (fcpf)
);

CREATE TABLE PACIENTE (
pcpf VARCHAR (11) PRIMARY KEY REFERENCES PESSOA (cpf)
);


CREATE TABLE CONSULTORIO (
andar INT NOT NULL,
numero INT NOT NULL,
PRIMARY KEY (andar, numero),
departamento VARCHAR (50) REFERENCES DEPARTAMENTO(dnome),
fmedico VARCHAR(20) REFERENCES MEDICO(crm),
status VARCHAR(20)
);

CREATE TABLE SALA_CIRURGIA(
numero SERIAL PRIMARY KEY,
departamento VARCHAR (50) REFERENCES DEPARTAMENTO (dnome),
fmedico VARCHAR (20) REFERENCES MEDICO(crm),
fenfermeiro VARCHAR(20) REFERENCES ENFERMEIRO(coren),
status VARCHAR(20)
);


CREATE TABLE LEITO_CIRURGICO(
numero SERIAL PRIMARY KEY,
departamento VARCHAR (50) REFERENCES DEPARTAMENTO (dnome),
fenfermeiro VARCHAR(20) REFERENCES ENFERMEIRO(coren),
fpaciente VARCHAR(11) REFERENCES PACIENTE(pcpf),
status VARCHAR(20)
);


CREATE TABLE LEITO_UTI(
numero SERIAL PRIMARY KEY,
departamento VARCHAR (50) REFERENCES DEPARTAMENTO (dnome),
fenfermeiro VARCHAR(20) REFERENCES ENFERMEIRO(coren),
fpaciente VARCHAR(11) REFERENCES PACIENTE(pcpf),
status VARCHAR(20)
);

CREATE TABLE CONSULTA (
nmr_consulta SERIAL PRIMARY KEY,
horario TIME,
data DATE,
fpaciente VARCHAR(11) REFERENCES PACIENTE (pcpf),
fmedico VARCHAR(20) REFERENCES MEDICO(crm),
andar INT,
numero INT,
FOREIGN KEY (andar, numero) REFERENCES CONSULTORIO(andar, numero)
);


CREATE TABLE CIRURGIA(
nmr_cirurgia SERIAL PRIMARY KEY,
horario TIME,
data DATE,
fpaciente VARCHAR(11) REFERENCES PACIENTE (pcpf),
fmedico VARCHAR(20) REFERENCES MEDICO(crm),
fsala INT REFERENCES SALA_CIRURGIA(numero),
fenfermeiro VARCHAR(20) REFERENCES ENFERMEIRO(coren)
);

CREATE TABLE FUNCIONARIO_TRABALHA_EM(
cpf_funcionario VARCHAR(11) PRIMARY KEY REFERENCES FUNCIONARIO(fcpf),
nome_departamento VARCHAR(50) REFERENCES DEPARTAMENTO(dnome),
data_inicio DATE,
data_fim DATE
);

CREATE TABLE MEDICO_TRABALHA_CONSULTORIO(
crm_medico VARCHAR(20) PRIMARY KEY REFERENCES MEDICO(crm),
andar INT,
numero INT,
data_inicio DATE,
data_fim DATE,
FOREIGN KEY (andar, numero) REFERENCES CONSULTORIO(andar, numero)
);

CREATE TABLE ENFERMEIRO_TRABALHA_CONSULTORIO(
coren_enfermeiro VARCHAR(20) PRIMARY KEY REFERENCES ENFERMEIRO(coren),
andar INT,
numero INT,
data_inicio DATE,
data_fim DATE,
FOREIGN KEY (andar, numero) REFERENCES CONSULTORIO(andar, numero)
);

CREATE TABLE ENFERMEIRO_TRABALHA_SALA_CIRURGIA(
coren_enfermeiro VARCHAR(20) PRIMARY KEY REFERENCES ENFERMEIRO(coren),
sala_numero SERIAL REFERENCES SALA_CIRURGIA(numero),
data_inicio DATE,
data_fim DATE
);

CREATE TABLE ENFERMEIRO_TRABALHA_LEITO_CIRURGICO(
coren_enfermeiro VARCHAR(20) PRIMARY KEY REFERENCES ENFERMEIRO(coren),
leito_numero SERIAL REFERENCES LEITO_CIRURGICO(numero),
data_inicio DATE,
data_fim DATE
);
CREATE TABLE ENFERMEIRO_TRABALHA_LEITO_UTI(
coren_enfermeiro VARCHAR(20) PRIMARY KEY REFERENCES ENFERMEIRO(coren),
leito_uti_numero SERIAL REFERENCES LEITO_UTI(numero),
data_inicio DATE,
data_fim DATE
);

CREATE TABLE CONSELHO_PRESIDENTE(
cpf_presidente VARCHAR(11) PRIMARY KEY REFERENCES PESSOA(cpf)
);
